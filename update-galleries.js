const fs = require('fs');
const path = require('path');

const OTHER_PROJECTS_NAME = 'Other Projects';

// Configuration for all the dynamic galleries on the portfolio
const galleriesConfig = [
    {
        dir: 'ApWebWorld',
        output: 'ap-web-world-data.js',
        globalVar: 'apWebData'
    },
    {
        dir: 'Aura Circle',
        output: 'aura-circle-data.js',
        globalVar: 'auraData'
    }
];

// Supported media extensions
const mediaExtensions = new Set(['.png', '.jpg', '.jpeg', '.gif', '.mp4', '.webm', '.svg', '.webp']);

function isMediaFile(filename) {
    const ext = path.extname(filename).toLowerCase();
    return mediaExtensions.has(ext);
}

function processGallery(config) {
    const data = {
        brands: []
    };

    let otherProjects = [];

    // Ensure directory exists
    if (!fs.existsSync(config.dir)) {
        console.error(`Error: Directory '${config.dir}' not found. Skipping...`);
        return;
    }

    const items = fs.readdirSync(config.dir, { withFileTypes: true });

    items.forEach(item => {
        const itemPath = path.join(config.dir, item.name);

        if (item.isDirectory()) {
            // It's a brand folder
            const brandFolderItems = fs.readdirSync(itemPath, { withFileTypes: true });
            const mediaFiles = [];

            brandFolderItems.forEach(file => {
                if (file.isFile() && isMediaFile(file.name)) {
                    // Use forward slashes for web paths
                    mediaFiles.push(`${config.dir}/${item.name}/${file.name}`);
                }
            });

            if (mediaFiles.length > 0) {
                data.brands.push({
                    id: item.name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
                    name: item.name,
                    cover: mediaFiles[0], // Use first media file as cover
                    items: mediaFiles
                });
            }
        } else if (item.isFile() && isMediaFile(item.name)) {
            // It's a root level media file
            otherProjects.push(`${config.dir}/${item.name}`);
        }
    });

    // Add "Other Projects" if there are any root level files
    if (otherProjects.length > 0) {
        data.brands.push({
            id: OTHER_PROJECTS_NAME.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
            name: OTHER_PROJECTS_NAME,
            cover: otherProjects[0],
            items: otherProjects
        });
    }

    // Sort brands alphabetically (with 'Other Projects' at the end)
    data.brands.sort((a, b) => {
        if (a.name === OTHER_PROJECTS_NAME) return 1;
        if (b.name === OTHER_PROJECTS_NAME) return -1;
        return a.name.localeCompare(b.name);
    });

    const jsContent = `// Auto-generated by update-galleries.js\nwindow.${config.globalVar} = ${JSON.stringify(data, null, 2)};`;
    fs.writeFileSync(config.output, jsContent);
    console.log(`✅ Successfully generated ${config.output} with ${data.brands.length} brands (from '${config.dir}').`);
}

// Run for all configured galleries
galleriesConfig.forEach(config => {
    console.log(`Processing gallery: ${config.dir}...`);
    processGallery(config);
});
